import asyncio
import os
import sys
from pathlib import Path

# Configure UTF-8 encoding for Windows console to handle emojis safely (ERR-ENC-02)
if sys.platform == "win32":
    try:
        sys.stdout.reconfigure(encoding='utf-8')
    except AttributeError:
        pass

def find_project_root() -> Path:
    """Walk up from current file to dynamically locate the root directory containing path_rules.md."""
    current = Path(__file__).resolve().parent
    for _ in range(10):
        if (current / "intelligence" / "path_rules.md").exists():
            return current
        current = current.parent
    # Dynamic parent fallback
    this_file = Path(__file__).resolve()
    for parent in [this_file.parent] + list(this_file.parents):
        if (parent / "intelligence" / "path_rules.md").exists():
            return parent
    return this_file.parent

# Dynamically set paths relative to the found project root
project_root = find_project_root()
sys.path.append(str(project_root))
sys.path.append(str(project_root / "services/ai-brain"))

try:
    from omni_parser import scan_omni_directory, UniversalNode
except ImportError:
    scan_omni_directory = None
    UniversalNode = None

async def generate_JKAI_MAP():
    if scan_omni_directory is None:
        print("[WARNING]: omni_parser not available in this environment.")
        return

    print("[JKAI ZENITH-MAP]: Starting project mapping for JKAI ZENITH...")
    
    # Scan main directories under project root
    scan_dirs = [
        str(project_root / "core"),
        str(project_root / "services"),
        str(project_root / "intelligence"),
        str(project_root / "scripts"),
    ]
    
    all_nodes = []
    for d in scan_dirs:
        if os.path.exists(d):
            print(f"🔍 [SCANNING]: {d}")
            nodes = await scan_omni_directory(d)
            all_nodes.extend(nodes)
            
    print(f"📊 [NODES-FOUND]: {len(all_nodes)} nodes identified.")
    
    # Generate Map File under project root
    map_file = project_root / "JKAI_MAP_GRAPH.md"
    
    content = [
        "# 🗺️ JKAI ZENITH PROJECT MAP GRAPH",
        "**The Sovereign Architect's View of the JKAI Zenith Ecosystem**",
        "",
        "## 🏛️ CORE COMPONENTS",
        "| Category | Node | Path | Links |",
        "| :--- | :--- | :--- | :--- |"
    ]
    
    # Group by type
    by_type = {}
    for node in all_nodes:
        t = node.file_type
        if t not in by_type: by_type[t] = []
        by_type[t].append(node)
        
    for t, nodes in sorted(by_type.items()):
        for node in nodes[:20]: # Limit to 20 per type for brevity in the main map
            links = ", ".join(node.links_to[:5])
            content.append(f"| {t} | {node.name} | `{node.file}` | {links} |")
            
    content.append("\n## 🧬 NEURAL LINKS (SOP & PROTOCOLS)")
    # Extract protocols specifically
    protocols = [n for n in all_nodes if "protocol" in n.file.lower()]
    for p in protocols:
        content.append(f"- **{p.name}**: `{p.file}`")
        
    content.append("\n---")
    content.append("*Sovereign Property of Master LeeTrung. Generated by Antigravity AI for Personal Navigation.* 🏛️🦾🚀")
    
    with open(map_file, "w", encoding="utf-8") as f:
        f.write("\n".join(content))
        
    print(f"✅ [MAP-GENERATED]: {map_file}")

if __name__ == "__main__":
    asyncio.run(generate_JKAI_MAP())
