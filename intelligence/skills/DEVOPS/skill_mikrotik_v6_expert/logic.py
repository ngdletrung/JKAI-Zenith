def validate_v6_script(script_text: str) -> Dict[str, Any]:
    """
    Kiểm tra tính an toàn và chuẩn xác của script RouterOS v6.
    """
    issues = []
    checks = {
        "has_bridge": "/interface bridge add" in script_text,
        "has_lan_ip": "/ip address add" in script_text,
        "has_dhcp_server": "/ip dhcp-server add" in script_text,
        "has_nat_masquerade": "action=masquerade" in script_text,
        "has_dns_allow": "allow-remote-requests=yes" in script_text,
        "has_firewall_filter": "/ip firewall filter add" in script_text,
    }

    if not checks["has_nat_masquerade"]:
        issues.append("Thiếu quy tắc NAT Masquerade: Máy trạm trong mạng LAN sẽ không thể ra Internet.")
    if checks["has_dns_allow"] and not checks["has_firewall_filter"]:
        issues.append("Cảnh báo bảo mật: Đã bật DNS Allow Remote Requests nhưng thiếu Firewall Filter chặn cổng 53 từ WAN (nguy cơ bị lợi dụng DNS Amplification Attack).")

    return {
        "valid": len(issues) == 0,
        "checks": checks,
        "issues": issues,
    }
