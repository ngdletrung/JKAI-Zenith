def generate_v6_setup_script(
    wan_type: str = "dhcp",
    wan_interface: str = "ether1",
    lan_ports: Optional[List[str]] = None,
    lan_bridge_name: str = "bridge-LAN",
    lan_gateway: str = "192.168.88.1/24",
    dhcp_pool_range: str = "192.168.88.10-192.168.88.254",
    dns_servers: str = "8.8.8.8,1.1.1.1",
    pppoe_user: Optional[str] = None,
    pppoe_pass: Optional[str] = None,
    static_wan_ip: Optional[str] = None,
    static_wan_gw: Optional[str] = None,
) -> str:
    """
    Tạo script cấu hình RouterOS v6 chuẩn xác 100% cú pháp.
    Hỗ trợ 3 chế độ WAN: dhcp, pppoe, static.
    """
    if lan_ports is None:
        lan_ports = ["ether2", "ether3", "ether4", "ether5"]

    lan_network = lan_gateway.split("/")[0]
    octets = lan_network.split(".")
    lan_network_base = f"{octets[0]}.{octets[1]}.{octets[2]}.0/24"
    lan_ip_only = octets[0] + "." + octets[1] + "." + octets[2] + "." + octets[3]

    lines = [
        "# ====================================================",
        "# MikroTik RouterOS v6 Sovereign Auto-Config Script",
        "# Generated by JKAI Network Cognitive Engine",
        "# ====================================================",
        "",
        "# 1. LAN Bridge Initialization",
        f"/interface bridge add name={lan_bridge_name} comment=\"LAN Core Bridge\"",
    ]

    for port in lan_ports:
        lines.append(f"/interface bridge port add bridge={lan_bridge_name} interface={port}")

    lines.extend([
        "",
        "# 2. LAN IP Addressing",
        f"/ip address add address={lan_gateway} interface={lan_bridge_name} network={octets[0]}.{octets[1]}.{octets[2]}.0 comment=\"LAN Gateway\"",
        "",
        "# 3. DHCP Server Configuration",
        f"/ip pool add name=pool-LAN ranges={dhcp_pool_range}",
        f"/ip dhcp-server add name=dhcp-LAN interface={lan_bridge_name} address-pool=pool-LAN disabled=no lease-time=12h",
        f"/ip dhcp-server network add address={lan_network_base} gateway={lan_ip_only} dns-server={lan_ip_only},{dns_servers} comment=\"LAN DHCP Network\"",
        "",
        "# 4. DNS Caching",
        f"/ip dns set allow-remote-requests=yes servers={dns_servers}",
    ])

    # WAN Configuration
    lines.append("")
    lines.append("# 5. WAN Configuration")
    nat_out_interface = wan_interface

    if wan_type.lower() == "pppoe":
        user_str = pppoe_user or "FTTH_ACCOUNT"
        pass_str = pppoe_pass or "FTTH_PASSWORD"
        lines.append(
            f"/interface pppoe-client add name=pppoe-out1 interface={wan_interface} "
            f"user=\"{user_str}\" password=\"{pass_str}\" add-default-route=yes disabled=no"
        )
        nat_out_interface = "pppoe-out1"
    elif wan_type.lower() == "static":
        if static_wan_ip:
            lines.append(f"/ip address add address={static_wan_ip} interface={wan_interface} comment=\"WAN Static IP\"")
        if static_wan_gw:
            lines.append(f"/ip route add gateway={static_wan_gw} distance=1 comment=\"Default Gateway\"")
    else:  # dhcp client
        lines.append(f"/ip dhcp-client add interface={wan_interface} disabled=no use-peer-dns=yes use-peer-ntp=yes add-default-route=yes comment=\"WAN DHCP Client\"")

    lines.extend([
        "",
        "# 6. Firewall & NAT Masquerade",
        f"/ip firewall nat add chain=srcnat out-interface={nat_out_interface} action=masquerade comment=\"NAT Masquerade WAN\"",
        "",
        "# Stateful Firewall Filter Protection",
        "/ip firewall filter add chain=input connection-state=established,related action=accept comment=\"Accept Established/Related Input\"",
        "/ip firewall filter add chain=input connection-state=invalid action=drop comment=\"Drop Invalid Input\"",
        f"/ip firewall filter add chain=input in-interface={lan_bridge_name} action=accept comment=\"Allow LAN to Router Management\"",
        "/ip firewall filter add chain=input protocol=icmp action=accept comment=\"Allow ICMP Ping Diagnostics\"",
        "/ip firewall filter add chain=input action=drop comment=\"Drop All Other WAN Input\"",
        "",
        "/ip firewall filter add chain=forward connection-state=established,related action=accept comment=\"Accept Established/Related Forward\"",
        "/ip firewall filter add chain=forward connection-state=invalid action=drop comment=\"Drop Invalid Forward\"",
        f"/ip firewall filter add chain=forward in-interface={lan_bridge_name} out-interface={nat_out_interface} action=accept comment=\"Allow LAN to Internet Forward\"",
        "/ip firewall filter add chain=forward action=drop comment=\"Drop All Other Forward\"",
        "",
        "# 7. Verification & Post-Check Command",
        "/ip route print",
        "/ip address print",
        "/ip dhcp-server print",
        "/ping count=4 8.8.8.8",
    ])

    return "\n".join(lines)


